"""The model API shared by providers; Jev decisions remain OpenRouter-only."""

from typing import Any, Protocol

from ..openrouter import ChatTurn, Completion, KeyInfo, TextCompletion, ToolPlan, Transcription


class ModelProvider(Protocol):
    async def complete_json(self, **kwargs: Any) -> Completion: ...
    async def chat_text(self, **kwargs: Any) -> TextCompletion: ...
    async def plan_tools(self, **kwargs: Any) -> ToolPlan: ...
    async def chat_tools(self, **kwargs: Any) -> ChatTurn: ...
    async def transcribe(self, **kwargs: Any) -> Transcription: ...
    async def key_info(self, key: str | None = None, timeout_s: float = 5) -> KeyInfo: ...
    async def models(self, timeout_s: float = 5) -> list[dict]: ...
    async def aclose(self) -> None: ...
